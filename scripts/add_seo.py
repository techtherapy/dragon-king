#!/usr/bin/env python3
"""Inject SEO metadata into every page.

Idempotent: the block is delimited by markers and replaced wholesale on each
run, so this can be re-run after the page generators without duplicating tags.
Existing <title> and <meta name="description"> are never rewritten — they are
read and reused for the social tags.

Run from the repo root:  python3 scripts/add_seo.py
"""
import html
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://dragonkingsutra.org"
OG_IMAGE = f"{SITE}/assets/og-image.jpg"
BEGIN = "<!-- SEO:begin (generated by scripts/add_seo.py — do not edit by hand) -->"
END = "<!-- SEO:end -->"

SUTRA_TITLE = "The Sutra Spoken by the Buddha on the Sea Dragon King"
GURU = "His Holiness Living Buddha Lian Sheng"

# page -> (og:type, priority, changefreq, extra JSON-LD builder key)
PAGES = {
    "index.html":        ("website", "1.0", "monthly", "home"),
    "read.html":         ("article", "0.9", "yearly",  "book"),
    "about.html":        ("article", "0.8", "yearly",  "about"),
    "treasure-vase-yoga.html":   ("article", "0.8", "yearly", "practice"),
    "treasure-vase-wishes.html": ("article", "0.7", "yearly", "wishes"),
    "nagas-and-dragon-kings.html": ("article", "0.7", "yearly", "nagas"),
    "his-holiness-living-buddha-lian-sheng.html": ("profile", "0.7", "yearly", "person"),
    "refuge.html":       ("article", "0.7", "yearly",  "page"),
    "contact.html":      ("website", "0.4", "yearly",  "page"),
}
NOINDEX = {"404.html"}

CRUMBS = {
    "en": {"home": "Home", "read": "Read the Sutra", "about": "About the Sutra",
           "practice": "Practice", "wishes": "Wishes in the Treasure Vase",
           "practice_h": "The Dragon King Treasure Vase Yoga",
           "wishes_h": "Wishes in the Dragon King Treasure Vase Practice",
           "nagas": "Nagas & Dragon Kings"},
    "es": {"home": "Inicio", "read": "Leer el Sutra", "about": "Acerca del Sutra",
           "practice": "Práctica", "wishes": "Deseos en el Jarrón del Tesoro",
           "practice_h": "El Yoga del Jarrón del Tesoro del Rey Dragón",
           "wishes_h": "Deseos en la práctica del Jarrón del Tesoro del Rey Dragón",
           "nagas": "Nagas y Reyes Dragones"},
}


def organization():
    return {
        "@type": "Organization",
        "name": "True Buddha School",
        "url": "https://en.tbsn.org/",
    }


def person_guru():
    return {
        "@type": "Person",
        "name": GURU,
        "alternateName": ["Grandmaster Sheng-Yen Lu", "Lian Sheng", "蓮生活佛", "盧勝彥"],
        "jobTitle": "Root Guru of the True Buddha School",
        "birthDate": "1945",
        "birthPlace": {"@type": "Place", "name": "Chiayi, Taiwan"},
        "affiliation": organization(),
        "url": f"{SITE}/his-holiness-living-buddha-lian-sheng",
    }


def website():
    return {
        "@type": "WebSite",
        "@id": f"{SITE}/#website",
        "url": SITE + "/",
        "name": "Dragon King Sutra",
        "alternateName": "佛說海龍王經",
        "inLanguage": ["en", "zh-Hant"],
        "publisher": organization(),
    }


def book():
    return {
        "@type": "Book",
        "@id": f"{SITE}/#sutra",
        "name": SUTRA_TITLE,
        "alternateName": ["佛說海龍王經", "Sāgara-nāgarāja-paripṛcchā Sūtra"],
        "translator": {"@type": "Person", "name": "Dharmarakṣa", "alternateName": "竺法護"},
        "inLanguage": ["zh-Hant", "en"],
        "genre": "Mahayana Buddhist scripture",
        "numberOfPages": 4,
        "about": [
            {"@type": "Thing", "name": "Mahayana Buddhism"},
            {"@type": "Thing", "name": "Dragon Kings"},
            {"@type": "Thing", "name": "Vajrayana"},
        ],
        "url": f"{SITE}/read",
    }


def article(url, headline, description, author_is_guru=True, image=OG_IMAGE, lang="en"):
    node = {
        "@type": "Article",
        "headline": headline,
        "description": description,
        "image": image,
        "url": url,
        "isPartOf": {"@id": f"{SITE}/#website"},
        "inLanguage": lang,
    }
    if author_is_guru:
        node["author"] = person_guru()
    return node


def breadcrumb(*crumbs):
    return {
        "@type": "BreadcrumbList",
        "itemListElement": [
            {"@type": "ListItem", "position": i + 1, "name": name, "item": url}
            for i, (name, url) in enumerate(crumbs)
        ],
    }


def jsonld_for(key, page, url, title, desc, lang="en"):
    """Returns the @graph list for a page."""
    if key == "home":
        return [website(), book(), person_guru()]
    home = SITE + ("/es/" if lang == "es" else "/")
    crumb = CRUMBS[lang]
    if key == "book":
        b = book()
        b["description"] = desc
        return [website(), b,
                breadcrumb((crumb["home"], home), (crumb["read"], url))]
    if key == "about":
        return [article(url, title, desc, author_is_guru=False, lang=lang),
                {"@type": "Book", "@id": f"{SITE}/#sutra"},
                breadcrumb((crumb["home"], home), (crumb["about"], url))]
    if key == "practice":
        a = article(url, crumb["practice_h"], desc, lang=lang)
        a["about"] = {"@type": "Thing", "name": "Dragon King Treasure Vase Yoga 龍王寶瓶法"}
        return [a, breadcrumb((crumb["home"], home), (crumb["practice"], url))]
    if key == "wishes":
        a = article(url, crumb["wishes_h"], desc, lang=lang)
        a["isPartOf"] = {"@type": "Book", "name": "A Solitary Bird in the Void",
                         "alternateName": "虛空中的孤鳥", "bookEdition": "Book 146",
                         "author": person_guru()}
        return [a, breadcrumb((crumb["home"], home), (crumb["wishes"], url))]
    if key == "nagas":
        a = article(url, title, desc, author_is_guru=False, lang=lang)
        return [a, breadcrumb((crumb["home"], home), (crumb["nagas"], url))]

    if key == "person":
        return [person_guru(),
                breadcrumb((crumb["home"], home), (GURU, url))]
    return [{"@type": "WebPage", "url": url, "name": title, "description": desc,
             "isPartOf": {"@id": f"{SITE}/#website"}, "inLanguage": lang}]


def json_dumps(obj, indent=2):
    """Minimal deterministic JSON writer (keeps key order, escapes for <script>)."""
    import json
    text = json.dumps(obj, ensure_ascii=False, indent=indent)
    # a literal </script> inside JSON-LD would close the tag early
    return text.replace("</", "<\\/")


def canonical_path(page, lang="en"):
    """about.html -> /about   (html_handling: auto-trailing-slash serves both)
    The Spanish twin of the same page lives under /es/."""
    prefix = "" if lang == "en" else "/es"
    if page == "index.html":
        return prefix + "/" if prefix else "/"
    return prefix + "/" + page[:-len(".html")]


def build_block(page, title, desc, lang="en"):
    if page in NOINDEX:
        return (f'{BEGIN}\n'
                f'<meta name="robots" content="noindex, follow">\n'
                f'<meta name="theme-color" content="#070e1a">\n'
                f'{END}')

    og_type, _prio, _freq, key = PAGES[page]
    url = SITE + canonical_path(page, lang)
    url_en = SITE + canonical_path(page, "en")
    url_es = SITE + canonical_path(page, "es")
    graph = jsonld_for(key, page, url, title, desc, lang)
    ld = {"@context": "https://schema.org", "@graph": graph}

    t = html.escape(title, quote=True)
    d = html.escape(desc, quote=True)
    lines = [
        BEGIN,
        f'<link rel="canonical" href="{url}">',
        f'<link rel="alternate" hreflang="en" href="{url_en}">',
        f'<link rel="alternate" hreflang="es" href="{url_es}">',
        f'<link rel="alternate" hreflang="x-default" href="{url_en}">',
        '<meta name="robots" content="index, follow, max-image-preview:large">',
        '<meta name="theme-color" content="#070e1a">',
        '',
        f'<meta property="og:type" content="{og_type}">',
        f'<meta property="og:url" content="{url}">',
        f'<meta property="og:title" content="{t}">',
        f'<meta property="og:description" content="{d}">',
        f'<meta property="og:image" content="{OG_IMAGE}">',
        '<meta property="og:image:width" content="1200">',
        '<meta property="og:image:height" content="630">',
        f'<meta property="og:image:alt" content="A golden dragon coiled around a flaming pearl beneath a radiant Buddha — {html.escape(SUTRA_TITLE, quote=True)}">',
        '<meta property="og:site_name" content="Dragon King Sutra">',
        f'<meta property="og:locale" content="{"es_LA" if lang == "es" else "en_US"}">',
        f'<meta property="og:locale:alternate" content="{"en_US" if lang == "es" else "es_LA"}">',
        '<meta property="og:locale:alternate" content="zh_TW">',
        '',
        '<meta name="twitter:card" content="summary_large_image">',
        f'<meta name="twitter:title" content="{t}">',
        f'<meta name="twitter:description" content="{d}">',
        f'<meta name="twitter:image" content="{OG_IMAGE}">',
        '',
        f'<script type="application/ld+json">\n{json_dumps(ld)}\n</script>',
        END,
    ]
    return "\n".join(lines)


TITLE_RE = re.compile(r"<title>(.*?)</title>", re.S)
DESC_RE = re.compile(r'<meta name="description" content="(.*?)">', re.S)


def process(path: Path, lang: str = "en") -> str:
    s = path.read_text(encoding="utf-8")
    page = path.name

    m = TITLE_RE.search(s)
    if not m:
        return f"{page}: no <title>, skipped"
    title = html.unescape(m.group(1).strip())
    dm = DESC_RE.search(s)
    desc = html.unescape(dm.group(1).strip()) if dm else title

    block = build_block(page, title, desc, lang)

    # replace an existing block, else insert before the icon link (stable anchor)
    if BEGIN in s:
        s = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), block, s, flags=re.S)
        action = "updated"
    else:
        anchor = '<link rel="icon"'
        assert anchor in s, f"{page}: no icon link to anchor to"
        s = s.replace(anchor, block + "\n" + anchor, 1)
        action = "inserted"

    path.write_text(s, encoding="utf-8")
    return f"{'es/' if lang == 'es' else ''}{page}: {action}"


def sitemap():
    urls = []
    for page, (_t, prio, freq, _k) in PAGES.items():
        en = SITE + canonical_path(page, "en")
        es = SITE + canonical_path(page, "es")
        for loc in (en, es):
            urls.append(
                "  <url>\n"
                f"    <loc>{loc}</loc>\n"
                f'    <xhtml:link rel="alternate" hreflang="en" href="{en}"/>\n'
                f'    <xhtml:link rel="alternate" hreflang="es" href="{es}"/>\n'
                f'    <xhtml:link rel="alternate" hreflang="x-default" href="{en}"/>\n'
                f"    <changefreq>{freq}</changefreq>\n"
                f"    <priority>{prio}</priority>\n"
                "  </url>"
            )
    xml = ('<?xml version="1.0" encoding="UTF-8"?>\n'
           '<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9"\n'
           '        xmlns:xhtml="http://www.w3.org/1999/xhtml">\n'
           + "\n".join(urls) + "\n</urlset>\n")
    (ROOT / "sitemap.xml").write_text(xml, encoding="utf-8")
    return f"sitemap.xml: {len(urls)} urls ({len(PAGES)} pages x 2 languages)"


def robots():
    txt = ("User-agent: *\n"
           "Allow: /\n"
           "\n"
           f"Sitemap: {SITE}/sitemap.xml\n")
    (ROOT / "robots.txt").write_text(txt, encoding="utf-8")
    return "robots.txt written"


if __name__ == "__main__":
    for page in list(PAGES) + sorted(NOINDEX):
        print(" ", process(ROOT / page))
    for page in PAGES:
        print(" ", process(ROOT / "es" / page, lang="es"))
    print(" ", sitemap())
    print(" ", robots())
